create schema if not exists private;
create or replace function private.is_seller(uid uuid default auth.uid())
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (select 1 from public.profiles p where p.id = uid and p.role = 'seller');
$$;
revoke all on function private.is_seller(uuid) from public;
grant usage on schema private to authenticated;
grant execute on function private.is_seller(uuid) to authenticated;

