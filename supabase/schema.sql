  seller_id = auth.uid() or private.is_order_buyer(order_id, auth.uid())
);

-- Checkout transacional: confere estoque, cria pedido, baixa estoque e limpa o carrinho.
create or replace function public.quex_create_order(p_items jsonb, p_delivery_address text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  order_id uuid;
  buyer_name text;
  entry jsonb;
  product_row public.produto%rowtype;
  qty numeric;
  total numeric := 0;
begin
  if uid is null then raise exception 'Usuário não autenticado.' using errcode = '42501'; end if;
  if jsonb_array_length(coalesce(p_items, '[]'::jsonb)) = 0 then raise exception 'Carrinho vazio.'; end if;

  select full_name into buyer_name from public.profiles where id = uid;
  if not exists (select 1 from public.profiles where id = uid and role = 'buyer') then
    raise exception 'Apenas compradores podem finalizar pedidos.' using errcode = '42501';
  end if;
  if coalesce(trim(p_delivery_address), '') = '' then raise exception 'Endereço de entrega obrigatório.'; end if;

  for entry in select * from jsonb_array_elements(p_items)
  loop
    qty := greatest(0, (entry ->> 'quantity')::numeric);
    if qty <= 0 then raise exception 'Quantidade inválida.'; end if;

    select * into product_row from public.produto where id = (entry ->> 'product_id')::bigint for update;
    if not found then raise exception 'Produto não encontrado.'; end if;
    if product_row.ativo is not true then raise exception 'Produto indisponível: %', product_row.nome; end if;
    if product_row.quantidade < qty then raise exception 'Estoque insuficiente para: %', product_row.nome; end if;
    total := total + (product_row.preco * qty);
  end loop;

  insert into public.orders (buyer_id, buyer_name, total, status, delivery_address)
  values (uid, buyer_name, total, 'pending', trim(p_delivery_address))
  returning id into order_id;

  for entry in select * from jsonb_array_elements(p_items)
  loop
    qty := (entry ->> 'quantity')::numeric;
    select * into product_row from public.produto where id = (entry ->> 'product_id')::bigint for update;

    insert into public.order_items (order_id, product_id, seller_id, seller_name, product_name, quantity, unit_price, subtotal)
    values (order_id, product_row.id, product_row.vendedor_id, product_row.vendedor_nome, product_row.nome, qty, product_row.preco, qty * product_row.preco);

    update public.produto
    set quantidade = quantidade - qty,
        ativo = case when quantidade - qty <= 0 then false else ativo end,
        updated_at = now()
    where id = product_row.id;

    delete from public.cart_items where buyer_id = uid and product_id = product_row.id;
  end loop;

  update public.orders set updated_at = now() where id = order_id;
  return (select to_jsonb(o) from public.orders o where o.id = order_id);
end;
$$;
revoke all on function public.quex_create_order(jsonb, text) from public;
grant execute on function public.quex_create_order(jsonb, text) to authenticated;

