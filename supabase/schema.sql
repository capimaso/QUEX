create index if not exists produto_ativo_idx on public.produto(ativo);
create index if not exists produto_vendedor_idx on public.produto(vendedor_id);
create index if not exists produto_especie_idx on public.produto(especie);
create index if not exists produto_categoria_idx on public.produto(categoria);

create table if not exists public.cart_items (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.produto(id) on delete cascade,
  product_name text not null,
  product_price numeric(12,2) not null,
  product_image text,
  seller_name text,
  quantity numeric(12,2) not null default 1 check (quantity > 0),
  subtotal numeric(12,2) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(buyer_id, product_id)
);

create index if not exists cart_items_buyer_idx on public.cart_items(buyer_id);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid not null references auth.users(id) on delete restrict,
  buyer_name text,
  total numeric(12,2) not null default 0,
  status text not null default 'pending' check (status in ('pending','paid','preparing','dispatched','delivered','cancelled')),
  delivery_address text not null default '',
  tracking_code text,
  delivery_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_buyer_idx on public.orders(buyer_id);
create index if not exists orders_status_idx on public.orders(status);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.produto(id) on delete restrict,
  seller_id uuid references auth.users(id) on delete set null,
  seller_name text,
  product_name text not null,
  quantity numeric(12,2) not null check (quantity > 0),
  unit_price numeric(12,2) not null,
  subtotal numeric(12,2) not null,
  created_at timestamptz not null default now()
);

create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists order_items_seller_idx on public.order_items(seller_id);

-- Perfil automático após cadastro pelo Supabase Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role, cpf, cpf_cnpj, phone, business_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'role', 'buyer'),
    nullif(new.raw_user_meta_data ->> 'cpf', ''),
    nullif(new.raw_user_meta_data ->> 'cpf_cnpj', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    nullif(new.raw_user_meta_data ->> 'business_name', '')
  )
  on conflict (id) do update set
    email = excluded.email,
    full_name = excluded.full_name,
    role = excluded.role,
    cpf = excluded.cpf,
    cpf_cnpj = excluded.cpf_cnpj,
    phone = excluded.phone,
    business_name = excluded.business_name,
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

