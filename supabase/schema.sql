create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text not null default '',
  role text not null default 'buyer' check (role in ('buyer','seller')),
  cpf text,
  cpf_cnpj text,
  phone text not null default '',
  business_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists full_name text not null default '';
alter table public.profiles add column if not exists role text not null default 'buyer';
alter table public.profiles add column if not exists cpf text;
alter table public.profiles add column if not exists cpf_cnpj text;
alter table public.profiles add column if not exists phone text not null default '';
alter table public.profiles add column if not exists business_name text;
alter table public.profiles add column if not exists created_at timestamptz not null default now();
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

create unique index if not exists profiles_cpf_unique on public.profiles (cpf) where cpf is not null and cpf <> '';
create unique index if not exists profiles_cpf_cnpj_unique on public.profiles (cpf_cnpj) where cpf_cnpj is not null and cpf_cnpj <> '';
create index if not exists profiles_role_idx on public.profiles(role);

create table if not exists public.produto (
  id bigint generated by default as identity primary key,
  vendedor_id uuid references auth.users(id) on delete set null,
  vendedor_email text,
  vendedor_nome text,
  nome text not null,
  categoria text not null default 'peixe' check (categoria in ('peixe','iguaria')),
  especie text not null default '',
  descricao text,
  preco numeric(12,2) not null check (preco > 0),
  quantidade numeric(12,2) not null default 0 check (quantidade >= 0),
  unidade text not null default 'kg' check (unidade in ('kg','unit','dozen')),
  ativo boolean not null default true,
  fotos_url text,
  tem_espinha boolean not null default false,
  tipo_agua text not null default 'doce' check (tipo_agua in ('doce','salgada')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

